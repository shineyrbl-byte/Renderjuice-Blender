# ---------------------------------------------------------------- mesh helpers
def make_obj(name, kind, mat=None, loc=(0, 0, 0), scale=(1, 1, 1), smooth_shade=False, **kw):
    ops = {
        'sphere': bpy.ops.mesh.primitive_uv_sphere_add,
        'cube': bpy.ops.mesh.primitive_cube_add,
        'cyl': bpy.ops.mesh.primitive_cylinder_add,
        'cone': bpy.ops.mesh.primitive_cone_add,
        'torus': bpy.ops.mesh.primitive_torus_add,
    }
    ops[kind](location=loc, **kw)
    ob = bpy.context.active_object
    ob.name = name
    ob.scale = scale
    if mat:
        ob.data.materials.append(mat)
    if smooth_shade:
        for p in ob.data.polygons:
            p.use_smooth = True
    return ob


def make_text(name, body, mat, size=1.0, align='CENTER', loc=(0, 0, 0), rot=(0, 0, 0), extrude=0.0):
    cu = bpy.data.curves.new(name, 'FONT')
    cu.body = body
    cu.size = size
    cu.align_x = align
    cu.align_y = 'CENTER'
    cu.extrude = extrude
    ob = link(bpy.data.objects.new(name, cu))
    ob.location = loc
    ob.rotation_euler = rot
    ob.data.materials.append(mat)
    return ob


# ---------------------------------------------------------------- geometry nodes instancer
def gn_instancer(name, points, scales, instance, mat, rotation=(0, 0, 0)):
    """Point cloud built in Python -> Geometry Nodes instances a ring or box on
    every point, scaled per point by the 'bscale' attribute."""
    ng = bpy.data.node_groups.new(name + 'GN', 'GeometryNodeTree')
    ng.interface.new_socket(name='Geometry', in_out='INPUT', socket_type='NodeSocketGeometry')
    ng.interface.new_socket(name='Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N, L = ng.nodes, ng.links
    gi, go = N.new('NodeGroupInput'), N.new('NodeGroupOutput')
    if instance == 'ring':
        c1 = N.new('GeometryNodeCurvePrimitiveCircle')
        c1.inputs['Radius'].default_value = 1.0
        c1.inputs['Resolution'].default_value = 96
        c2 = N.new('GeometryNodeCurvePrimitiveCircle')
        c2.inputs['Radius'].default_value = 0.018
        c2.inputs['Resolution'].default_value = 8
        cm = N.new('GeometryNodeCurveToMesh')
        L.new(c1.outputs['Curve'], cm.inputs['Curve'])
        L.new(c2.outputs['Curve'], cm.inputs['Profile Curve'])
        geo = cm.outputs['Mesh']
    else:
        cube = N.new('GeometryNodeMeshCube')
        geo = cube.outputs['Mesh']
    sm = N.new('GeometryNodeSetMaterial')
    sm.inputs['Material'].default_value = mat
    L.new(geo, sm.inputs['Geometry'])
    iop = N.new('GeometryNodeInstanceOnPoints')
    L.new(gi.outputs[0], iop.inputs['Points'])
    L.new(sm.outputs['Geometry'], iop.inputs['Instance'])
    iop.inputs['Rotation'].default_value = rotation
    na = N.new('GeometryNodeInputNamedAttribute')
    na.data_type = 'FLOAT_VECTOR'
    na.inputs['Name'].default_value = 'bscale'
    L.new(na.outputs[0], iop.inputs['Scale'])
    L.new(iop.outputs['Instances'], go.inputs[0])

    me = bpy.data.meshes.new(name)
    me.from_pydata(points, [], [])
    at = me.attributes.new('bscale', 'FLOAT_VECTOR', 'POINT')
    at.data.foreach_set('vector', [c for s in scales for c in s])
    ob = link(bpy.data.objects.new(name, me))
    mod = ob.modifiers.new('Instancer', 'NODES')
    mod.node_group = ng
    return ob


