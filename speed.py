F_MORAL = 362
VMAX = 45.0                 # metres per frame at top speed (~Mach 3)

random.seed(7)


def clamp(x, a=0.0, b=1.0):
    return max(a, min(b, x))


def smooth(x):
    x = clamp(x)
    return x * x * (3 - 2 * x)


def lerp(a, b, t):
    return a + (b - a) * t


def lerp3(a, b, t):
    return tuple(lerp(a[i], b[i], t) for i in range(3))


def wobble(f, amp, seed):
    return amp * (0.6 * math.sin(f * 1.7 + seed) + 0.3 * math.sin(f * 3.1 + seed * 2.3)
                  + 0.1 * math.sin(f * 7.3 + seed * 0.7))


# ---------------------------------------------------------------- motion profile
vel = [0.0] * (F_END + 2)
pos = [0.0] * (F_END + 2)
for f in range(1, F_END + 2):
    if F_LAUNCH <= f <= F_TOP:
        tau = (f - F_LAUNCH) / (F_TOP - F_LAUNCH)
        a = 3.2
        v = VMAX * (0.85 * (math.exp(a * tau) - 1) / (math.exp(a) - 1) + 0.15 * min(1.0, tau * 6))
    elif F_TOP < f <= F_STOP:
        u = (f - F_TOP) / (F_STOP - F_TOP)
        v = VMAX * (1 - u) ** 2.5
    else:
        v = 0.0
    vel[f] = v
    pos[f] = pos[f - 1] + v
S_END = pos[F_STOP]
FINISH_Y = S_END - 12
PODIUM_Y = S_END + 5
KMH = [int(round(v * FPS * 3.6)) for v in vel]
