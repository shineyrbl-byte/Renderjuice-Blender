def setup_compositor():
    """Bloom glow via the compositor (Blender 4.2+ removed EEVEE's built-in bloom)."""
    try:
        if hasattr(scene, 'compositing_node_group'):
            ng = bpy.data.node_groups.new('Comp', 'CompositorNodeTree')
            ng.interface.new_socket(name='Image', in_out='OUTPUT', socket_type='NodeSocketColor')
            scene.compositing_node_group = ng
            out = ng.nodes.new('NodeGroupOutput')
        else:
            scene.use_nodes = True
            ng = scene.node_tree
            ng.nodes.clear()
            out = ng.nodes.new('CompositorNodeComposite')
        rl = ng.nodes.new('CompositorNodeRLayers')
        gl = ng.nodes.new('CompositorNodeGlare')
        try_set(gl, 'glare_type', 'BLOOM', 'FOG_GLOW')
        try_set(gl, 'quality', 'HIGH')
        try_set(gl, 'threshold', 1.0)
        try_set(gl, 'size', 8)
        try_set(gl, 'mix', 0.0)
        for name, val in (('Type', 'Bloom'), ('Quality', 'High'), ('Threshold', 1.0), ('Size', 0.45),
                          ('Strength', 0.35)):
            s = gl.inputs.get(name)
            if s is not None:
                try:
                    s.default_value = val
                except Exception as e:
                    print('[speed] glare input', name, e)
        ng.links.new(rl.outputs['Image'], gl.inputs['Image'])
        ng.links.new(gl.outputs['Image'], out.inputs[0])
        print('[speed] compositor bloom ok')
    except Exception as e:
        print('[speed] compositor setup failed:', e)


